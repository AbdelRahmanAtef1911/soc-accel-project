#!/usr/bin/env python3
"""
extract_layers.py - read the MLPerf Tiny INT8 .tflite models and write the
layer table used by the benchmark program (sw/layers.h) plus a CSV copy.

Every CONV_2D, DEPTHWISE_CONV_2D and FULLY_CONNECTED operator becomes one row.
Each row also gets its GEMM view (M x K) * (K x N):
    CONV / PW : M = Ho*Wo (output pixels), K = R*S*C (one filter), N = filters
    FC        : M = 1,                     K = inputs,             N = outputs
    DW        : not a GEMM -> always runs on the CPU in this project

Usage (inside the container):
    pip install tflite --break-system-packages
    python3 extract_layers.py <tiny-repo>/benchmark/training  ../sw/layers.h  layers_mlperf_tiny.csv
"""
import csv
import os
import sys

try:
    import tflite
except ImportError:
    sys.exit("missing package: pip install tflite --break-system-packages")

MODELS = [
    # (short name, path below benchmark/training)
    ("resnet8", "image_classification/trained_models/pretrainedResnet_quant.tflite"),
    ("dscnn",   "keyword_spotting/trained_models/kws_ref_model.tflite"),
    ("mbnet",   "visual_wake_words/trained_models/vww_96_int8.tflite"),
]

T_CONV, T_PW, T_DW, T_FC = 0, 1, 2, 3
TYPE_NAME = {T_CONV: "CONV", T_PW: "PW", T_DW: "DW", T_FC: "FC"}


def same_pad(in_size, k, s):
    out = (in_size + s - 1) // s
    total = max((out - 1) * s + k - in_size, 0)
    return out, total // 2


def valid_out(in_size, k, s):
    return (in_size - k) // s + 1


def layers_of(model_name, path):
    buf = open(path, "rb").read()
    m = tflite.Model.GetRootAsModel(buf, 0)
    g = m.Subgraphs(0)
    rows = []
    for i in range(g.OperatorsLength()):
        op = g.Operators(i)
        code = m.OperatorCodes(op.OpcodeIndex())
        b = max(code.BuiltinCode(), code.DeprecatedBuiltinCode())
        if b not in (tflite.BuiltinOperator.CONV_2D,
                     tflite.BuiltinOperator.DEPTHWISE_CONV_2D,
                     tflite.BuiltinOperator.FULLY_CONNECTED):
            continue
        tin = g.Tensors(op.Inputs(0))
        tw = g.Tensors(op.Inputs(1))
        tout = g.Tensors(op.Outputs(0))
        ishape = tin.ShapeAsNumpy().tolist()
        wshape = tw.ShapeAsNumpy().tolist()
        oshape = tout.ShapeAsNumpy().tolist()

        if b == tflite.BuiltinOperator.FULLY_CONNECTED:
            n_out, k_in = wshape
            rows.append(dict(model=model_name, name=f"{model_name}_fc{len(rows)}", type=T_FC,
                             H=1, W=1, C=k_in, R=1, S=1, K=n_out, sh=1, sw=1, pt=0, pl=0,
                             Ho=1, Wo=1))
            continue

        opt_t = op.BuiltinOptions()
        if b == tflite.BuiltinOperator.CONV_2D:
            o = tflite.Conv2DOptions()
        else:
            o = tflite.DepthwiseConv2DOptions()
        o.Init(opt_t.Bytes, opt_t.Pos)
        sh, sw = o.StrideH(), o.StrideW()
        _, H, W, C = ishape
        if b == tflite.BuiltinOperator.CONV_2D:
            K, R, S, _ = wshape
        else:
            _, R, S, K = wshape
        if o.Padding() == tflite.Padding.SAME:
            Ho, pt = same_pad(H, R, sh)
            Wo, pl = same_pad(W, S, sw)
        else:
            Ho, Wo, pt, pl = valid_out(H, R, sh), valid_out(W, S, sw), 0, 0
        assert [Ho, Wo] == oshape[1:3], (model_name, i, Ho, Wo, oshape)
        if b == tflite.BuiltinOperator.DEPTHWISE_CONV_2D:
            t = T_DW
        elif R == 1 and S == 1 and sh == 1 and sw == 1:
            t = T_PW
        else:
            t = T_CONV
        rows.append(dict(model=model_name, name=f"{model_name}_{TYPE_NAME[t].lower()}{len(rows)}",
                         type=t, H=H, W=W, C=C, R=R, S=S, K=K, sh=sh, sw=sw, pt=pt, pl=pl,
                         Ho=Ho, Wo=Wo))
    for r in rows:
        if r["type"] == T_DW:
            r["M"], r["Kg"], r["N"] = r["Ho"] * r["Wo"], r["R"] * r["S"], r["K"]
            r["macs"] = r["Ho"] * r["Wo"] * r["R"] * r["S"] * r["K"]
        else:
            r["M"], r["Kg"], r["N"] = r["Ho"] * r["Wo"], r["R"] * r["S"] * r["C"], r["K"]
            r["macs"] = r["M"] * r["Kg"] * r["N"]
    return rows


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    root, out_h, out_csv = sys.argv[1:]
    rows = []
    for name, rel in MODELS:
        rows += layers_of(name, os.path.join(root, rel))

    cols = ["model", "name", "type", "H", "W", "C", "R", "S", "K", "sh", "sw", "pt", "pl",
            "Ho", "Wo", "M", "Kg", "N", "macs"]
    with open(out_csv, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in rows:
            w.writerow([TYPE_NAME[r[c]] if c == "type" else r[c] for c in cols])

    with open(out_h, "w") as f:
        f.write("/* Generated by workloads/extract_layers.py from the MLPerf Tiny INT8 models. */\n")
        f.write("#ifndef LAYERS_H\n#define LAYERS_H\n#include <stdint.h>\n\n")
        f.write("enum { L_CONV = 0, L_PW = 1, L_DW = 2, L_FC = 3 };\n\n")
        f.write("typedef struct {\n  const char *model, *name;\n  uint8_t type;\n"
                "  uint16_t H, W, C, R, S, K, sh, sw, pt, pl, Ho, Wo;\n} layer_t;\n\n")
        f.write("static const layer_t LAYERS[] = {\n")
        for r in rows:
            f.write('  {"%s", "%s", %d, %d,%d,%d, %d,%d,%d, %d,%d,%d,%d, %d,%d},\n' % (
                r["model"], r["name"], r["type"], r["H"], r["W"], r["C"], r["R"], r["S"], r["K"],
                r["sh"], r["sw"], r["pt"], r["pl"], r["Ho"], r["Wo"]))
        f.write("};\n#define NUM_LAYERS (sizeof(LAYERS) / sizeof(LAYERS[0]))\n\n#endif\n")

    tot = {}
    for r in rows:
        tot.setdefault(r["model"], [0, 0])
        tot[r["model"]][0] += 1
        tot[r["model"]][1] += r["macs"]
    for k, (n, macs) in tot.items():
        print(f"{k:8s} {n:3d} layers  {macs/1e6:7.2f} M MACs")
    print(f"wrote {out_h} and {out_csv}")


if __name__ == "__main__":
    main()
